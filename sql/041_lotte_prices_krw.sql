-- Цены лотов Lotte переведены в ВОНЫ.
-- Запустить в Supabase Dashboard → SQL Editor ПОСЛЕ 040.
--
-- ─── Что изменилось ──────────────────────────────────────────────────────
--
-- Витрина-посредник принимает параметр ?currency=KRW и отдаёт цену в вонах:
-- ₩38 784 000 там, где по умолчанию показывала $28 894. Курс её пересчёта
-- (≈1342.3 ₩/$) нам неизвестен и не контролируется, а вона у аукциона
-- исходная. Поэтому цены Lotte теперь ложатся в ту же колонку, что у KCar —
-- start_price_krw, — и отдельная долларовая колонка больше не нужна.
--
-- ⚠️ Старые значения в price_usd ОБНУЛЯЕМ, а не оставляем «на всякий случай».
--    Это снимок чужого курса на дату загрузки: он не пересчитывается, ни с чем
--    не сверяется и через месяц будет расходиться с ценой в вонах на проценты.
--    Колонка, которая молча хранит устаревшую цену, опаснее отсутствующей —
--    ровно так в проекте уже ломались цены на витрине (см. постмортемы).
--
-- Саму колонку не удаляем: DROP COLUMN необратим, а стоимость пустой колонки
-- нулевая. Понадобится снова — вернётся с ясным смыслом.

UPDATE auction_lots SET price_usd = NULL WHERE price_usd IS NOT NULL;

COMMENT ON COLUMN auction_lots.price_usd IS
  'НЕ ИСПОЛЬЗУЕТСЯ с 12.09.2026. Цена всех площадок хранится в '
  'start_price_krw: витрина Lotte отдаёт воны по ?currency=KRW, а доллар был '
  'её собственным пересчётом по неизвестному курсу. Доллары для показа '
  'считаются нашим курсом в одном месте, как требуют правила проекта.';

COMMENT ON COLUMN auction_lots.start_price_krw IS
  'Стартовая цена торгов, ВОНЫ — у ВСЕХ площадок. У KCar приходит от самого '
  'аукциона, у Lotte — с витрины-посредника по ?currency=KRW. '
  'Систематически ниже цены продажи: медиана превышения +13.8% по 9 651 '
  'состоявшейся сделке KCar. Показывать её как цену машины нельзя — нужен '
  'прогноз из auction_results (для Lotte его нет: истории торгов этой '
  'площадки у нас не существует).';
