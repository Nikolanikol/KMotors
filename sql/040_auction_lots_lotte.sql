-- Поддержка лотов аукциона Lotte в auction_lots.
-- Запустить в Supabase Dashboard → SQL Editor ПОСЛЕ 039.
--
-- ─── Почему цена в ОТДЕЛЬНОЙ колонке, а не в start_price_krw ──────────────
--
-- У KCar стартовая цена приходит в вонах от самого аукциона. У Lotte своего
-- публичного API нет (проверено 12.09.2026: на lotteautoauction.net открыты
-- только вход, ЧАВО и новости), поэтому лоты берутся с витрины-посредника, а
-- она подписывает цену «Starting Price» и отдаёт её В ДОЛЛАРАХ, пересчитав по
-- своему курсу.
--
-- ⚠️ Класть это в start_price_krw нельзя ни в каком виде. Колонка объявлена
--    как воны, её читают estimate.ts и витрина; доллары там означали бы цену
--    в 1400 раз ниже — и не в отчёте, а в цене, которую увидит клиент.
--    Обратный пересчёт по нашему курсу тоже не годится: мы не знаем курса, по
--    которому считала витрина, и получили бы третье число, не равное ни
--    старту, ни доллару. Правило то же, что в CLAUDE.md про цены: конвертации
--    живут в одном месте, а чужая валюта хранится как есть.
--
-- ⚠️ Прогноз молотка для Lotte НЕ строится и строиться не должен: истории
--    прошедших торгов по этой площадке у нас нет — auction_results наполняется
--    из списочного API KCar, которого у Lotte нет. estimate.ts отбирает
--    сделки без фильтра по площадке, так что премия KCar к лоту Lotte
--    неприменима: это разные аукционы с разной механикой.

ALTER TABLE auction_lots ADD COLUMN IF NOT EXISTS price_usd integer;
ALTER TABLE auction_lots ADD COLUMN IF NOT EXISTS status_image_url text;

COMMENT ON COLUMN auction_lots.price_usd IS
  'Цена старта торгов В ДОЛЛАРАХ, как её отдаёт витрина-посредник («Starting '
  'Price»). Только для source = lotte: у KCar старт приходит в вонах и лежит '
  'в start_price_krw. Курс пересчёта витрины нам неизвестен, поэтому число '
  'хранится как есть и показывается долларами.';

COMMENT ON COLUMN auction_lots.status_image_url IS
  'Диаграмма состояния кузова — ГОТОВАЯ КАРТИНКА, по одной на лот '
  '(imgs.dokanmazad.com/auction/lotte_status_<N>.jpeg, ~70 КБ). ⚠️ Витрина '
  'отдаёт не панельные данные, а заранее отрисованное изображение: в её '
  'поле reports у лотов Lotte пусто (проверено на 33 лотах), картинка лежит '
  'в accidentImages. Следствие: показать можно, отфильтровать по состоянию '
  'нельзя. У KCar наоборот — панели приходят структурой в defect_parts.';
