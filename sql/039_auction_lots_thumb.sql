-- Миниатюра лота из СПИСОЧНОГО ответа площадки.
-- Запустить в Supabase Dashboard → SQL Editor ПОСЛЕ 038.
--
-- ─── Зачем отдельная колонка, если есть photos ───────────────────────────
--
-- `photos` заполняет ТОЛЬКО добор (enrich): он скрейпит стороннюю витрину,
-- идёт ~35 минут на 1700 страниц и запускается раз в неделю. До него у лота
-- нет ни одной картинки, а витрине она нужна с первого же прогона.
--
-- Оказалось, что списочный ответ getAuctionCarList_ajax.do несёт миниатюры
-- сам — поля THUMBNAIL (370px) и THUMBNAIL_MOBILE (640px) относительными
-- путями вида «2039/CA20390012/CA20390012v23mqs5zp_640.JPG». В наших типах
-- их не было, и toLot их выбрасывал. Теперь картинка есть у КАЖДОГО лота
-- сразу после обычной синхронизации, без добора.
--
-- ⚠️ Путь НЕ ВЫВОДИТСЯ из external_id: в имени файла сидит случайный токен
--    («v23mqs5z»). Поэтому URL надо хранить, а не собирать на лету.
--
-- ⚠️ Храним АБСОЛЮТНЫЙ URL, а не путь. Таблица рассчитана на несколько
--    площадок (source: kcar | lotte | sk), хост у них разный, и склейка
--    «наш базовый + их путь» сломается на первой же не-KCar строке.
--
-- ⚠️ Картинка отдаётся ХОТЛИНКОМ, к себе не копируется (решение владельца
--    12.09.2026). Проверено curl'ом: площадка отвечает 200 и без Referer, и
--    с чужим Referer — проверки нет. Но content-type она отдаёт неверный,
--    image/gif при расширении .JPG, поэтому через next/image такие адреса
--    гонять нельзя: оптимизатор ориентируется на тип. В разметке обычный
--    <img loading="lazy">, он же и есть настоящий хотлинк — трафик идёт
--    мимо нашего сервера.

ALTER TABLE auction_lots ADD COLUMN IF NOT EXISTS thumb_url text;

COMMENT ON COLUMN auction_lots.thumb_url IS
  'Миниатюра лота, АБСОЛЮТНЫЙ адрес на сервере площадки (640px). Приходит '
  'в списочном ответе, поэтому есть у всех лотов сразу, в отличие от photos, '
  'которые заполняет только добор. Отдаётся хотлинком: к себе не копируем, '
  'через next/image не гоняем (площадка врёт content-type).';
