// Событие «открыть корзину» — отдельным лёгким модулем, без кода панели.
//
// ⚠️ Шапка слушает это событие всегда, а саму панель (`CartDrawer`) грузит лениво.
// Если держать константу в CartDrawer.tsx, импорт константы потянет за собой всю
// панель в общий бандл — ради чего ленивая загрузка и затевалась.

/** Событие «открыть корзину» — чтобы кнопки на страницах не тянули состояние шапки. */
export const CART_OPEN_EVENT = "kmotors_cart_open";

export function openCartDrawer() {
  window.dispatchEvent(new Event(CART_OPEN_EVENT));
}
