/**
 * Экранирование запроса Encar (`q=`) для подстановки в URL.
 *
 * ⚠️ Названия пунктов фильтра содержат «+» — все гибриды: «가솔린+전기 2500cc»,
 * «디젤+전기», «LPG+전기». Сырой «+» в строке запроса читается как ПРОБЕЛ: Encar
 * искал «가솔린 전기 2500cc», находил 0 машин, а у уровня «Модификация» не было
 * вариантов вовсе (у Kia Carnival 4 поколения это 49% машин). То же ломают «&» и
 * «#»: они обрывают значение `q`.
 *
 * ⚠️ «%» НЕ экранируем намеренно: часть запросов приходит уже закодированной
 * (`Simple.keyword(%EA%B0…)` в getString, запросы savedSearches/similarCars) —
 * повторное кодирование испортило бы их. В готовой строке «+», «&» и «#» в сыром
 * виде встретиться не могут, поэтому замена безопасна для обоих видов.
 */
export function escapeEncarQuery(query: string): string {
  return query.replace(/[+&#]/g, (ch) => encodeURIComponent(ch));
}
