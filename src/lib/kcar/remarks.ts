function conditionRu(raw: string): string | null {
  const s = raw.trim();
  if (!s) return null;

  const keys = KEYS.exec(s);
  if (keys) return `ключей: ${keys[1]}`;

  const n = COUNT.exec(s);
  let out = s;
  // Пробелы вокруг подстановки обязательны — иначе токены слипаются.
  for (const [ko, ru] of CONDITION) out = out.split(ko).join(` ${ru} `);
  out = out
    .replace(/\s*\d+\s*EA/g, "")
    .replace(/\s+([),])/g, "$1")
    .replace(/\s+/g, " ")
    .replace(/^[\s/,]+|[\s/,]+$/g, "");

  if (n && n[1] !== "1") out += ` ×${n[1]}`;
  return out || null;
}

export function parseRemarks(text: string | null | undefined): ParsedRemarks {
  const t = (text ?? "").trim();
  if (!t) return { notices: [], conditions: [], blockedExport: false, docDays: null };

  const blocks = t.split("★").map((b) => b.trim()).filter(Boolean);
  const head = blocks.slice(0, -1);
  const tail = blocks.length ? blocks[blocks.length - 1] : "";
  const hay = head.length ? head.join(" ") : t;

  const notices: ParsedRemarks["notices"] = [];
  const seen = new Set<string>();
  for (const [ko, ru, level] of NOTICES) {
    if (hay.includes(ko) && !seen.has(ru)) {
      notices.push({ text: ru, level });
      seen.add(ru);
    }
  }

  // Последний блок считаем описью, только если он похож на перечисление:
  // иначе в состояние попадёт хвост очередного уведомления.
  const conditions: string[] = [];
  if (tail && (tail.includes(",") || tail.length < 90)) {
    for (const item of tail.split(",")) {
      const ru = conditionRu(item);
      if (ru) conditions.push(ru);
    }
  }

  const days = DOC_DAYS.exec(t);
  return {
    notices,
    conditions,
    blockedExport: notices.some((n) => n.level === "block"),
    docDays: days ? Number(days[1]) : null,
  };
}
