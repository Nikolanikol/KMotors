/**
 * Минимальная таможенная стоимость по объёму двигателя, ALL.
 *
 * ⚠ ЭТА ТАБЛИЦА НЕ ПОДТВЕРЖДЕНА НИ ОДНИМ ПРОГОНОМ. Калькулятор-эталон её
 * не применяет вовсе: при цене 800 EUR и объёме 1998 см³ он посчитал НДС
 * от фактических 74 488 ALL, а не от 406 000 (кейс al-08). Значения взяты
 * из сводки владельца по тарифам 2026 года и включены в расчёт по его
 * решению — таблица работает заградительным барьером против занижения цены.
 *
 * Следствие: ни одна из шести границ — 1400, 1900, 2500, 3000, 4500 —
 * эталоном не проверяется и проверена быть не может, пока эталон тот же.
 *
 * Границы трактуются как «объём не больше верхнего значения», вслед за
 * демо-калькулятором: 1400 см³ попадает в первый бракет, а не во второй.
 * Это тоже предположение — исходная формулировка «до 1400 / от 1400 до 1900»
 * на самой границе неоднозначна.
 */
export const MIN_CUSTOMS_VALUE_ALL: ReadonlyArray<{
  maxCc: number;
  minAll: number;
}> = [
  { maxCc: 1400, minAll: 162_500 },
  { maxCc: 1900, minAll: 250_000 },
  { maxCc: 2500, minAll: 406_000 },
  { maxCc: 3000, minAll: 500_000 },
  { maxCc: 4500, minAll: 625_000 },
  { maxCc: Number.POSITIVE_INFINITY, minAll: 1_000_000 },
];

/** Максимум таблицы. Нужен инварианту: минимум не может дотянуть до порога роскоши. */
export const MIN_CUSTOMS_VALUE_MAX_ALL = 1_000_000;

export function minimumCustomsValueAll(volumeCc: number): number {
  for (const bracket of MIN_CUSTOMS_VALUE_ALL) {
    if (volumeCc <= bracket.maxCc) return bracket.minAll;
  }
  return MIN_CUSTOMS_VALUE_MAX_ALL;
}

