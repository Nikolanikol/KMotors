/**
 * Округление до целого лека — часть расчёта, а не оформление.
 *
 * Обычное, не вверх: кейс al-12 даёт точный НДС 81 229,164 и показывает
 * 81 229. При округлении вверх было бы 81 230.
 */
export function roundAll(value: number): number {
  return Math.round(value);
}

