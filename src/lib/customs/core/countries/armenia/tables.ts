function pickByCc<T extends { maxCc: number }>(
  brackets: ReadonlyArray<T>,
  volumeCc: number,
): T {
  for (const bracket of brackets) {
    if (volumeCc <= bracket.maxCc) return bracket;
  }
  return brackets[brackets.length - 1];
}

/** Бракет ставок по объёму. Гибрид считается по бензиновой таблице. */
export function specificBracket(volumeCc: number, isDiesel: boolean) {
  return pickByCc(isDiesel ? DIESEL_BRACKETS : PETROL_BRACKETS, volumeCc);
}

export function ecoRate(age: number): number {
  for (const bracket of ECO_BRACKETS) {
    if (age <= bracket.maxAge) return bracket.rate;
  }
  return ECO_BRACKETS[ECO_BRACKETS.length - 1].rate;
}

/**
 * Округление до целого драма — часть расчёта, а не оформление.
 *
 * У драма нет разменной единицы в обиходе, и эталон округляет каждую статью
 * до целой единицы валюты ещё до сложения. Складывать неокруглённые статьи
 * и округлять итог — другой порядок и другой результат.
 */
export function roundAmd(value: number): number {
  return Math.round(value);
}
