// Чистые правила категорий запчастей — без обращений к БД и next/cache,
// поэтому модуль безопасно импортировать из "use client" компонентов.
// Всё, что ходит в Supabase, живёт в partsCategories.ts (server-only).

/**
 * Порог тонкого контента: категории меньше рендерятся, но отдают noindex
 * и не попадают в sitemap.
 */
export const CAT_MIN_PARTS = 30;

// Категории-корзины: «Прочее двигатель», «Мелкие детали АКПП», «Кронштейны
// мелкие» и т.п. Внутренние вёдра, под которые никто не ищет; как посадочные
// бесполезны. Плюс small-parts-staging — служебное название, которому не
// место в публичном интерфейсе.
//
// Правило по слагу, а не по названию: колонки-флага в parts_categories нет,
// а эти шаблоны покрывают ровно 25 категорий из 176 и ни одной лишней
// (проверено по полной выгрузке дерева). Слаг переживёт перевод названий.
const BUCKET_SLUG = /(^small-|-small-|-other$|staging)/;

export const isBucketCategory = (slug: string) => BUCKET_SLUG.test(slug);

/**
 * В parts_categories один слаг может принадлежать ДВУМ разным категориям:
 * body-panels — это и «Кузовные панели» под «Кузов» (id 18001), и одноимённая
 * ветка под «Крепёж и расходные» (id 900942). URL один, значит открыть можно
 * только одну; без явного правила выбор зависел бы от порядка строк из БД,
 * а в sitemap попадал бы дубль <loc>.
 *
 * Владельцем слага считаем меньший id — исходную категорию, а не позже
 * добавленную. Товары «проигравшей» ветки не теряются: они остаются
 * в поддереве своего корня и доступны через его пагинацию.
 */
export function ownsSlug<T extends { id: number; slug: string }>(node: T, all: T[]): boolean {
  const sameSlug = all.filter((c) => c.slug === node.slug);
  return sameSlug.every((c) => c.id >= node.id);
}
