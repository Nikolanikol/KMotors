"use client";

// Выпадашка, которая отправляет форму сразу при выборе.
//
// Зачем. Каталог — обычная GET-форма без клиентского JS, и это осознанно
// (адрес = состояние фильтра). Но список моделей строится на сервере по
// выбранной марке, а пока форма не отправлена, сервер марку не знает: модель
// оставалась серой с «сначала марка», и казалось, что фильтр сломан (живой
// случай 02.10.2026). Отправка при выборе марки — единственное, что здесь
// нужно от клиента, поэтому клиентский только этот компонент, а не страница.
//
// requestSubmit, а не submit: первый проходит обычный путь отправки формы
// (событие submit, проверка полей), второй его обходит.

import type { ComponentProps } from "react";

export default function AutoSubmitSelect(props: ComponentProps<"select">) {
  return (
    <select
      {...props}
      onChange={(e) => {
        props.onChange?.(e);
        e.currentTarget.form?.requestSubmit();
      }}
    />
  );
}
